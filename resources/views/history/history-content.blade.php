                            <p>
                                Originally part of the Province of Zambales, the town of Mabini was initially called
                                “Balincaguin” which came from the
                                Sambalic phrase “Bali Lan Caguin” which translates to “abode of bats” as the caves found
                                in the area were inhabited by
                                bats.
                            </p>
                            <p>
                                Although the town was founded by Don Isidro Puzon in 1800, Balincaguin is speculated to
                                be first discovered by
                                Augustinian Recollects in 1610. To honor one of the country’s greatest heroes Apolinario
                                Mabini, considered to be the
                                brains of the revolution against the Spanish empire, the town of Balincaguin was renamed
                                Mabini in 1930.
                            </p>
                            <p>
                                Mabini is part of the first congressional district of the Province of Pangasinan. It has
                                a land area of 29,101 hectares
                                and a population of 26,454 according to the 2020 census.
                            </p>
