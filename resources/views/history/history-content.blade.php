                        <div class="col-12 history-text" style="text-align: justify;">
                            <p>
                                Tourism-wise, the town of Mabini is famous for its caves. Visitors can visit the
                                Cacupangan Cave System, a
                                four-kilometer subterranean gem complete with an underground river and beautifully
                                carved limestone formations of
                                stalagmites and stalactites. The cave system has multiple entrances that span over
                                several barangays. One is the
                                Binmatya Cave, popular for its rimstone formation. Other entrances to the Cacupangan
                                Cave System are the Ara-saas and
                                Sto. Rosario Caves. Mabini’s flora and fauna above ground are also a must-see when
                                visiting Mabini with Balincaguin
                                River and Timore Mountain on top of the list.
                            </p>
                            <p>
                                The place is believed to have been founded in 1610 by Spanish missionaries from the
                                Order of Augustinian Recollects. In
                                1800, Balincaquin became a town under Don Isidro Puzon who is believed to be the
                                founder. Some of its population (770
                                families) were Ilocanos who moved to the municipality due to its agricultural potential.
                                The site where these settlers
                                situated near the mountains used to be called "Conventa."
                            </p>
                            <p>
                                Agricultural produce like rice, mangoes, cashew nuts, and vegetables are the main
                                products produced in the agricultural
                                town of Mabini. Livestock and Poultry industries as well as baskets & sawali making are
                                also major contributors to its
                                economic output.
                            </p>
                            <p>
                                The municipality was merged with Alaminos, Bani, Anda, Dasol, Burgos, Bolinao and
                                Infanta in 1904 and presently
                                comprises the province's first district. In 1930, the town's name was changed to Mabini
                                in honor of hero Apolinario
                                Mabini.
                            </p>

                            <h2 class="history-sub-title fw-bold">Geography and Natural Landscape</h2>
                            <hr class="mb-4">
                            <p>
                                Nestled in the western part of Pangasinan, the Municipality of Mabini is blessed with a
                                rich and diverse physical
                                landscape. From fertile agricultural valleys to the rugged foothills of the Zambales
                                Mountain Range, Mabini’s geography
                                is a testament to the town's natural beauty and ecological wealth.
                            </p>

                            <h2 class="history-sub-title fw-bold">LOCATION AND LAND AREA</h2>
                            <hr class="mb-4">
                            <p>
                                Mabini is a landlocked municipality comprising 16 barangays. It covers a total land area
                                of 29,101 hectares (291.01
                                square kilometers), representing approximately 5.3% of the province's total landmass.
                                Strategically located, Mabini sits
                                roughly 48 kilometers southwest of the provincial capital, Lingayen, sharing borders
                                with the provinces of Zambales to
                                the west and Tarlac to the southwest.
                            </p>

