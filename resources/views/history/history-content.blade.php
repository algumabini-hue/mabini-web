                            <h2 class="history-sub-title fw-bold">TOPOGRAPHY AND TERRAIN</h2>
                            <hr class="mb-4">
                            <p>
                                The municipality offers a striking topographic transition. The town center (Poblacion)
                                and its surrounding barangays lie
                                on relatively flat and gently rolling terrain, sitting at a modest elevation of 20 to 50
                                meters above sea level. As you
                                move toward the western and southwestern boundaries, the landscape rises dramatically,
                                characterized by dense forests
                                and the majestic foothills of the Zambales Mountains.
                            </p>

                            <h2 class="history-sub-title fw-bold">NATURAL WONDERS AND WATERWAYS</h2>
                            <hr class="mb-4">
                            <p>
                                Mabini is widely celebrated for its spectacular subterranean networks, built upon
                                ancient limestone foundations.
                            </p>
                            <p>
                                <strong class="text-uppercase">The Cacupangan Cave System</strong><br>
                                Our crowning natural jewel, this four-kilometer underground
                                stretch features a subterranean
                                river, stunning rimstone pools, and intricate stalagmite and stalactite formations.
                                Other notable caves drawing nature
                                enthusiasts include the Binmatya, Ara-saas, and Sto. Rosario caves.
                            </p>
                            <p>
                                <strong class="text-uppercase">BALINCAGUIN RIVER AND MOUNT TIMORE</strong><br>
                                Above ground, the landscape is anchored by Mount
                                Timore and intersected by the
                                Balincaguin River, a vital waterway that provides essential irrigation to our thriving
                                ecosystems and local farms.
                            </p>
